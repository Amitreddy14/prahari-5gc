#!/usr/bin/env bash
# Resource profile: memory and CPU per container at several UE counts.
# Restarts the UE and provision services for each count, waits for registration,
# then samples `docker stats`. Writes a Markdown table to docs/results/testbed-profile.md.
#
#   cd testbed && bash scripts/profile.sh            # default counts: 10 50 100
#   bash scripts/profile.sh 10 25                    # custom counts
set -euo pipefail
export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL="*"

cd "$(dirname "$0")/.."
# Number of uesimtunN interfaces in the UE container (0 if none or not running).
# `grep -c` prints 0 AND exits 1 on no match, so `|| echo 0` would print "0" twice.
ue_tunnels() {
    local n
    n="$(docker compose exec -T ue sh -c 'ip -o link show | grep -c uesimtun || true' 2>/dev/null | tr -dc '0-9')"
    echo "${n:-0}"
}

counts=("$@")
[ "${#counts[@]}" -eq 0 ] && counts=(10 50 100)
out="../docs/results/testbed-profile.md"
mkdir -p "$(dirname "${out}")"

{
    echo "# Testbed resource profile"
    echo
    echo "Generated by \`testbed/scripts/profile.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo "Host: $(docker info --format '{{.OperatingSystem}}, {{.NCPU}} CPUs, {{.MemTotal}} bytes RAM' 2>/dev/null)."
    echo
} > "${out}"

for n in "${counts[@]}"; do
    echo "== ${n} UEs"
    PRAHARI_UE_COUNT="${n}" docker compose up -d --force-recreate provision ue >/dev/null
    deadline=$((SECONDS + 300))
    until [ "$(ue_tunnels)" -ge "${n}" ]; do
        if [ "${SECONDS}" -ge "${deadline}" ]; then
            echo "   timed out waiting for ${n} UEs" >&2
            break
        fi
        sleep 3
    done
    sleep 10   # let heartbeats and timers settle
    registered="$(ue_tunnels)"
    {
        echo "## ${n} UEs requested, ${registered} registered"
        echo
        echo "| Container | CPU % | Memory |"
        echo "|---|---|---|"
        mapfile -t ids < <(docker compose ps -q)
        docker stats --no-stream --format '| {{.Name}} | {{.CPUPerc}} | {{.MemUsage}} |' "${ids[@]}" | sort
        echo
    } >> "${out}"
done

echo "Wrote ${out}"
